#!/usr/bin/env python3
"""Generates the web app's game-code words from the Swift list.

The words live in `Sources/Model/GameCodeWords.swift` and that stays the single
source of truth: a code made in the app has to be joinable in a browser, which
means both clients must be drawing from the same vocabulary even though the two
words in any given code are chosen at random on whichever device made it.

Writes `web/src/lib/gameCodeWords.generated.ts`, which nothing should edit by
hand. Regenerate after changing the list:

    python3 Tools/make_web_game_codes.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Sources" / "Model" / "GameCodeWords.swift"
TARGET = ROOT / "web" / "src" / "lib" / "gameCodeWords.generated.ts"

ENTRY = re.compile(r'^\s*"([^"]+)",\s*$', re.M)


def main():
    if not SOURCE.exists():
        sys.exit(f"Missing {SOURCE}")

    words = ENTRY.findall(SOURCE.read_text())

    # The one thing a code cannot survive is a word that is not a word: it is
    # read out loud and typed back in, so anything but four plain lowercase
    # letters is a code somebody cannot share.
    for word in words:
        if not re.fullmatch(r"[a-z]{4}", word):
            sys.exit(f"Not four lowercase letters: {word!r}")
    if len(set(words)) != len(words):
        sys.exit("The list has a duplicate in it")
    if len(words) < 100:
        sys.exit(f"Only {len(words)} words: too few to make a code from")

    lines = [
        "// Generated by Tools/make_web_game_codes.py — do not edit.",
        "//",
        "// The words live in Sources/Model/GameCodeWords.swift, because a code",
        "// made in the app has to be joinable in a browser: both clients draw",
        "// from the same vocabulary. Regenerate after changing the list.",
        "",
        "/** Four-letter words game codes are built from. */",
        "export const GAME_CODE_WORDS: string[] = [",
    ]
    lines += [f"  {json.dumps(word)}," for word in words]
    lines += ["];", ""]

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))

    print(f"Wrote {TARGET.relative_to(ROOT)}")
    print(f"  {len(words)} words, {len(words) * (len(words) - 1):,} possible codes")


if __name__ == "__main__":
    main()
