#!/usr/bin/env python3
"""Generates the web app's Vibe Five categories from the Swift pack files.

The 1,100 prompts live in `Sources/Features/VibeFive/Packs/` as Swift string
arrays, and that stays the single source of truth — the app and the browser must
offer the same categories, and a second hand-maintained copy would drift.

Writes `web/src/games/five/prompts.generated.ts`, which nothing should edit by
hand. Regenerate after changing any pack:

    python3 Tools/make_web_packs.py
    python3 Tools/check_packs.py      # the same content, validated
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKS = ROOT / "Sources" / "Features" / "VibeFive" / "Packs"
TARGET = ROOT / "web" / "src" / "games" / "five" / "prompts.generated.ts"

# The Swift type name in each pack file, and the id the web app knows it by.
FILES = {
    "EverydayPrompts": "everyday",
    "FoodPrompts": "food",
    "AnimalsPrompts": "animals",
    "MoviesPrompts": "movies",
    "MusicPrompts": "music",
    "TVPrompts": "tv",
    "TravelPrompts": "travel",
    "SportsPrompts": "sports",
    "GamesPrompts": "games",
    "PeoplePrompts": "people",
    "RandomPrompts": "random",
}

# A Swift string literal inside the array, with its escapes.
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def read_prompts(path: pathlib.Path) -> list[str]:
    """Every string literal in the array.

    Parsed line by line rather than by finding the closing bracket: the
    declaration itself contains one (`[String]`), and a prompt could too.
    """
    lines = path.read_text().splitlines()
    start = next(i for i, line in enumerate(lines) if "static let all" in line)
    prompts = []
    for line in lines[start + 1:]:
        if line.strip() == "]":
            break
        for raw in LITERAL.findall(line):
            prompts.append(raw.replace('\\"', '"').replace("\\'", "'"))
    return prompts


def main() -> None:
    collected: dict[str, list[str]] = {}
    for type_name, pack_id in FILES.items():
        matches = list(PACKS.glob(f"{type_name}.swift"))
        if not matches:
            raise SystemExit(f"no pack file for {type_name}")
        prompts = read_prompts(matches[0])
        if not prompts:
            raise SystemExit(f"{type_name} produced no prompts")
        collected[pack_id] = prompts

    total = sum(len(v) for v in collected.values())
    lines = [
        "// Generated by Tools/make_web_packs.py — do not edit.",
        "//",
        "// The prompts themselves live in Sources/Features/VibeFive/Packs/ as Swift,",
        "// so the app and the browser cannot drift apart. Regenerate after changing",
        "// a pack, and run Tools/check_packs.py to validate the content itself.",
        "",
        "export const PROMPTS: Record<string, string[]> = {",
    ]
    for pack_id, prompts in collected.items():
        lines.append(f"  {pack_id}: [")
        for prompt in prompts:
            lines.append(f"    {json.dumps(prompt, ensure_ascii=False)},")
        lines.append("  ],")
    lines.append("};")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))
    print(f"{total} prompts across {len(collected)} packs -> {TARGET.relative_to(ROOT)}")
    for pack_id, prompts in collected.items():
        print(f"  {pack_id:<10} {len(prompts)}")


if __name__ == "__main__":
    sys.exit(main())
