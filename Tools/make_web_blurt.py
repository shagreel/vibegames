#!/usr/bin/env python3
"""Generates the web app's Similar Vibe packs from the Swift pack files.

The words live in `Sources/Features/VibeBlurt/Packs/` as Swift string arrays and
that stays the single source of truth. It matters more here than for Vibe Five:
the deck a browser deals is derived from the seed *and* the packs, so a second
hand-maintained copy that drifted by one word would put the describer and every
other screen in the room on different words.

Writes `web/src/games/blurt/words.generated.ts`, which nothing should edit by
hand. Regenerate after changing any pack:

    python3 Tools/make_web_blurt.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKS = ROOT / "Sources" / "Features" / "VibeBlurt" / "Packs"
PACK_TYPE = ROOT / "Sources" / "Features" / "VibeBlurt" / "BlurtPack.swift"
TARGET = ROOT / "web" / "src" / "games" / "blurt" / "words.generated.ts"

# The Swift type name in each pack file, and the id the web app knows it by.
FILES = {
    "FoodWords": "food",
    "AnimalsWords": "animals",
    "PlacesWords": "places",
    "HouseholdWords": "household",
    "PeopleWords": "people",
    "PlayWords": "play",
    "ActionsWords": "actions",
    "OccasionsWords": "occasions",
}

ENTRY = re.compile(r'^\s*"([^"]+)",\s*$', re.M)


def swift_strings(path):
    return ENTRY.findall(path.read_text())


def switch_values(source, property_name):
    """Every `case .x: return "y"` in one computed property of BlurtPack."""
    start = source.index(f"var {property_name}: String {{")
    end = source.index("\n    }", start)
    body = source[start:end]
    return dict(re.findall(r'case \.(\w+): return "([^"]*)"', body))


def main():
    pack_source = PACK_TYPE.read_text()
    titles = switch_values(pack_source, "title")
    symbols = switch_values(pack_source, "symbol")
    blurbs = switch_values(pack_source, "blurb")

    order = re.findall(r"^    case (\w+)$", pack_source, re.M)

    words = {}
    for type_name, pack_id in FILES.items():
        path = PACKS / f"{type_name}.swift"
        if not path.exists():
            sys.exit(f"Missing pack file: {path}")
        words[pack_id] = swift_strings(path)

    # The two lists have to describe the same eight packs, or the browser would
    # be missing words the phone has.
    if set(order) != set(words):
        sys.exit(f"BlurtPack cases {sorted(order)} do not match the pack files {sorted(words)}")

    for pack_id in order:
        for name, table in (("title", titles), ("symbol", symbols), ("blurb", blurbs)):
            if pack_id not in table:
                sys.exit(f"BlurtPack.{pack_id} has no {name}")

    total = sum(len(v) for v in words.values())
    lines = [
        "// Generated by Tools/make_web_blurt.py — do not edit.",
        "//",
        "// The words themselves live in Sources/Features/VibeBlurt/Packs/ as Swift,",
        "// because the deck is derived from the seed *and* the packs: a copy that",
        "// drifted by one word would put the describer and the rest of the room on",
        "// different words. Regenerate after changing a pack.",
        "",
        "export interface BlurtPackInfo {",
        "  id: string;",
        "  title: string;",
        "  symbol: string;",
        "  blurb: string;",
        "}",
        "",
        "/** Pack order, which is also the order words are concatenated in. */",
        "export const PACK_ORDER: string[] = [",
    ]
    lines += [f"  {json.dumps(p)}," for p in order]
    lines += [
        "];",
        "",
        "export const PACKS: Record<string, BlurtPackInfo> = {",
    ]
    for pack_id in order:
        lines += [
            f"  {json.dumps(pack_id)}: {{",
            f"    id: {json.dumps(pack_id)},",
            f"    title: {json.dumps(titles[pack_id])},",
            f"    symbol: {json.dumps(symbols[pack_id])},",
            f"    blurb: {json.dumps(blurbs[pack_id])},",
            "  },",
        ]
    lines += ["};", "", "export const PACK_WORDS: Record<string, string[]> = {"]
    for pack_id in order:
        lines.append(f"  {json.dumps(pack_id)}: [")
        lines += [f"    {json.dumps(word)}," for word in words[pack_id]]
        lines.append("  ],")
    lines += ["};", ""]

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))

    print(f"Wrote {TARGET.relative_to(ROOT)}")
    for pack_id in order:
        print(f"  {pack_id:12} {len(words[pack_id]):>3}")
    print(f"  {'total':12} {total:>3}")


if __name__ == "__main__":
    main()
